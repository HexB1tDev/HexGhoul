    /** Every skin there is for a girl ({@code girl}) or a boy. */
    public static List<Skin> of(boolean girl) {
        List<Skin> out = new ArrayList<>();
        for (Skin skin : ALL) {
            if (skin.girl() == girl) {
                out.add(skin);
            }
        }
        return out;
    }

    /** How far apart two skin tones look (RGB, weighted as the eye weighs them). */
    public static double distance(int a, int b) {
        double dr = ((a >> 16) & 255) - ((b >> 16) & 255);
        double dg = ((a >> 8) & 255) - ((b >> 8) & 255);
        double db = (a & 255) - (b & 255);
        return Math.sqrt((2.0 * dr * dr + 4.0 * dg * dg + 3.0 * db * db) / 9.0);
    }

    /** The skins a child of tone {@code tone} may wear: its sex's, no further from its tone than the nearest one plus {@link #SPREAD}. */
    public static List<Skin> near(boolean girl, int tone) {
        List<Skin> all = of(girl);
        double best = Double.MAX_VALUE;
        for (Skin skin : all) {
            best = Math.min(best, distance(skin.tone(), tone));
        }
        List<Skin> out = new ArrayList<>();
        for (Skin skin : all) {
            if (distance(skin.tone(), tone) <= best + SPREAD) {
                out.add(skin);
            }
        }
        return out;
    }

    /** The skin a child with {@code genome} wears all its life (null only if there are none for its sex). */
    public static Skin pick(Genome genome) {
        List<Skin> near = near(genome.gender().female(), genome.skin());
        if (near.isEmpty()) {
            return null;
        }
        long mixed = genome.seed() * 0x9E3779B97F4A7C15L;
        mixed ^= mixed >>> 31;
        return near.get((int)Math.floorMod(mixed, (long)near.size()));
    }
